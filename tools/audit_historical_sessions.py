#!/usr/bin/env python3
"""Compare historical observation exit attribution to each preserved session summary."""
import collections,json,sys
from pathlib import Path

root=Path(sys.argv[1]);out=Path(sys.argv[2]);out.mkdir(parents=True,exist_ok=True)
errors=[];batches=[];all_asns=collections.Counter();covered=0
for n in range(45):
    folder=root/f"vpn-shard-{n}"
    ss=list(folder.rglob("geosite-vpnobratno-summary.json"))
    oo=list(folder.rglob("vpnobratno-observations.jsonl"))
    if len(ss)!=1 or len(oo)!=1:
        errors.append(f"batch {n}: expected one summary and JSONL")
        continue
    d=json.loads(ss[0].read_text(encoding="utf-8"))
    observations=[json.loads(x) for x in oo[0].read_text(encoding="utf-8").splitlines() if x.strip()]
    exits={(str(x["asn"]),x["ip"]) for x in d.get("verified_exits",[])}
    by_exit=collections.Counter((str(x.get("vpn_asn")),x.get("vpn_exit_ip")) for x in observations)
    for k in by_exit:
        if k not in exits:errors.append(f"batch {n}: observed exit missing from summary {k}")
    if int(d.get("distinct_exit_asns",0))!=len({a for a,_ in exits}):errors.append(f"batch {n}: distinct exit ASN count mismatch")
    if d.get("measurements")!=len(observations):errors.append(f"batch {n}: measurements mismatch")
    if d.get("upstream_ref")!="30e797f05ddb8e38ccc2c44938b64846b4fce2fb":errors.append(f"batch {n}: transport revision mismatch")
    if len({a for a,_ in exits})<2:errors.append(f"batch {n}: fewer than two distinct session ASNs")
    for asn,ip in by_exit:all_asns[asn]+=by_exit[(asn,ip)]
    covered+=len(observations)
    batches.append({"batch":n,"measurement_count":len(observations),"verified_exits":[{"asn":a,"ip":ip,"observations":by_exit[(a,ip)]} for a,ip in sorted(exits)],"state":d.get("upstream_state"),"requested_exits":d.get("requested_exits")})
result={"source_run":45417945474,"shards_checked":len(batches),"observations_checked":covered,"asns":dict(all_asns),"errors":errors,"batches":batches,"limitations":["session summaries and observation exit attribution are generated by same software, not independent attestation","original run did not retain vpn_gate_raw.jsonl or provider metadata in shard artifacts","historical firewall traffic capture was not retained","source claims two metadata sources but source-level responses are not preserved in these artifacts"]}
(out/"historical-sessions.json").write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding="utf-8")
print(json.dumps({k:v for k,v in result.items() if k!="batches"},indent=2))
sys.exit(bool(errors))
